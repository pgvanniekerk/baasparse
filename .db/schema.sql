-- 3.3.1 U_USER — user accounts
CREATE TABLE IF NOT EXISTS U_USER (
  U_UID                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  U_USERNAME             TEXT        NOT NULL,
  U_DISPLAY_NAME         TEXT        NULL,
  U_EMAIL                TEXT        NULL,
  U_AUTH_SOURCE          TEXT        NOT NULL DEFAULT 'LOCAL',
  U_PASSWORD_HASH        TEXT        NULL,
  U_STATUS               TEXT        NOT NULL DEFAULT 'ACTIVE',
  U_MUST_CHANGE_PASSWORD BOOLEAN     NOT NULL DEFAULT FALSE,
  U_FAILED_LOGIN_COUNT   INT         NOT NULL DEFAULT 0,
  U_LOCKED_UNTIL         TIMESTAMPTZ NULL,
  U_PASSWORD_CHANGED_ON  TIMESTAMPTZ NULL,
  U_CREATED_BY           TEXT        NOT NULL,
  U_CREATED_ON           TIMESTAMPTZ NOT NULL DEFAULT now(),
  U_MODIFIED_BY          TEXT        NOT NULL,
