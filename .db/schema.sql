-- =============================================================================
-- baasparse — PostgreSQL install schema (baseline 0001_initial)
-- =============================================================================
-- Physical realisation of docs/technical-spec/03-database-design.md, following the
-- naming standard of docs/technical-spec/02-conventions.md §2.1 and the authoritative
-- 45-table registry in §2.2 (registry actually enumerates 50 tables — all are emitted
-- below, grouped Administration / Configuration / Operational).
--
-- Properties:
--   * Idempotent: CREATE ... IF NOT EXISTS everywhere; constraints inline in CREATE
--     TABLE (so IF NOT EXISTS covers them); the one circular FK and the audit trigger
--     are added under DO-guards / DROP-IF-EXISTS. Safe to re-run.
--   * Dependency-ordered: parents before children; the single RD<->RDV cycle is closed
--     by a trailing ALTER ... ADD CONSTRAINT.
--   * Identifiers are UPPER unquoted (PostgreSQL folds them to lowercase); nothing is
--     double-quoted, so the app can reference tables case-insensitively.
--
-- Requires PostgreSQL 15+ (NULLS NOT DISTINCT unique index on OS_OPERATIONAL_STATE,
-- §3.5.22). Tested against PostgreSQL 18.
-- =============================================================================

-- SQL schema (namespace) for all engine tables. This is the schema INSIDE your
-- database (which may be named anything, e.g. baasparseDB) — TS 02 §2.1 fixes it
-- to `baasparse`. The engine's search_path must match (see --db-schema).
CREATE SCHEMA IF NOT EXISTS baasparse;
SET search_path TO baasparse, public;

